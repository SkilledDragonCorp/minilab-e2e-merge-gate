#!/usr/bin/env bun
/**
 * Reads ci/upstream/spec.yml and writes scripts/upstream-test.sh with every
 * run: block from the local leg: check job; test job with node 24; install job
 * with pnpm 11. No hand-typed upstream commands.
 */
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parse as parseYaml } from "yaml";

const root = join(import.meta.dir, "..");
const yamlPath = join(root, "ci", "upstream", "spec.yml");
const outPath = join(root, "scripts", "upstream-test.sh");

type Step = {
  name?: string;
  uses?: string;
  run?: string;
  env?: Record<string, string>;
};

type Job = {
  steps?: Step[];
};

type Workflow = {
  env?: Record<string, string>;
  jobs?: Record<string, Job>;
};

function shellEscapeSingle(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function emitRun(step: Step, lines: string[]): void {
  const name = step.name ?? "run";
  lines.push(`echo '==> ${name.replace(/'/g, "")}'`);
  if (step.env) {
    for (const [k, v] of Object.entries(step.env)) {
      lines.push(`export ${k}=${shellEscapeSingle(String(v))}`);
    }
  }
  const body = step.run ?? "";
  lines.push("(");
  lines.push('  cd "$ROOT/upstream"');
  for (const line of body.split("\n")) {
    lines.push(`  ${line}`);
  }
  lines.push(")");
  lines.push("");
}

async function main(): Promise<void> {
  const text = await readFile(yamlPath, "utf8");
  const doc = parseYaml(text) as Workflow;
  const jobs = doc.jobs ?? {};
  const topEnv = doc.env ?? {};

  const lines: string[] = [];
  lines.push("#!/usr/bin/env bash");
  lines.push("# GENERATED by bun run scripts/extract-upstream-steps.ts — do not edit by hand.");
  lines.push("set -euo pipefail");
  lines.push('ROOT="$(cd "$(dirname "$0")/.." && pwd)"');
  lines.push('cd "$ROOT"');
  lines.push("export E2E_TELEMETRY_DISABLED=1");
  for (const [k, v] of Object.entries(topEnv)) {
    if (k === "E2E_TELEMETRY_DISABLED") continue;
    lines.push(`export ${k}=${shellEscapeSingle(String(v))}`);
  }
  lines.push("");
  lines.push('PIN="292cd0597c57b4929ad53919f0e4fe40ad87e095"');
  lines.push('actual="$(git -C upstream rev-parse HEAD)"');
  lines.push('if [[ "$actual" != "$PIN" ]]; then');
  lines.push('  echo "upstream pin mismatch: $actual" >&2');
  lines.push("  exit 1");
  lines.push("fi");
  lines.push("");

  for (const jobName of ["check", "test", "install"] as const) {
    const job = jobs[jobName];
    if (!job?.steps) throw new Error(`missing job ${jobName} in upstream YAML`);
    lines.push(`echo '==== job: ${jobName} ===='`);
    for (const step of job.steps) {
      if (!step.run) continue;
      let run = step.run;
      if (jobName === "test") run = run.replaceAll("${{ matrix.node }}", "24");
      if (jobName === "install") run = run.replaceAll("${{ matrix.pnpm }}", "11");
      emitRun({ ...step, run }, lines);
    }
    lines.push("");
  }

  lines.push('echo "upstream-test.sh finished ok"');
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, `${lines.join("\n")}\n`, "utf8");
  await chmod(outPath, 0o755);
  console.log(`wrote ${outPath}`);
}

await main();
